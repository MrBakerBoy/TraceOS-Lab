package services

import (
	"math"
	"time"
)

// RiskIndicator computes Grafana-style composite risk indicators.
//
// Design references:
//   - Google SRE saturation index (USE methodology)
//   - Grafana compound risk dashboards
//   - cAdvisor cgroup-limit-vs-actual OOM risk
//
// Composite indicators provide higher-dimension decision support beyond
// single-threshold alerts. Formula:
//
//	HealthScore = 100 - (SatIndex×40 + DepRiskScore×30 + BacklogGrowth×30)
type RiskIndicator struct {
	CPUWeight  float64
	MemWeight  float64
	ConnWeight float64
}

// RiskResult holds computed risk indicators.
type RiskResult struct {
	HealthScore      float64 `json:"health_score"`
	SaturationIndex  float64 `json:"saturation_index"`
	DependencyRisk   float64 `json:"dependency_risk"`
	BacklogGrowth    float64 `json:"backlog_growth"`
	OOMRiskRate      float64 `json:"oom_risk_rate"`
	CPUSaturationPct float64 `json:"cpu_saturation_pct"`
	MemSaturationPct float64 `json:"mem_saturation_pct"`
	FDSaturationPct  float64 `json:"fd_saturation_pct"`
	HealthLevel      string  `json:"health_level"`
	TrendDirection   string  `json:"trend_direction"`

	// OOM timeline annotation (cAdvisor style)
	OOMEvents       int       `json:"oom_events"`
	LastOOMAt       *time.Time `json:"last_oom_at,omitempty"`
	CFSThrottledMs  float64   `json:"cfs_throttled_ms"`
}

// AnomalyAlert represents a resource anomaly detected by the rule engine.
type AnomalyAlert struct {
	Rule         string  `json:"rule"`
	Condition    string  `json:"condition"`
	Probability  float64 `json:"probability"` // 0-1 Netdata-style confidence
	Severity     string  `json:"severity"`    // "info" | "warning" | "critical"
	Message      string  `json:"message"`
	TeachingHint string  `json:"teaching_hint,omitempty"`
	Timestamp    time.Time `json:"timestamp"`
}

// NewRiskIndicator creates a new risk indicator calculator with default weights.
func NewRiskIndicator() *RiskIndicator {
	return &RiskIndicator{
		CPUWeight:  0.40,
		MemWeight:  0.35,
		ConnWeight: 0.25,
	}
}

// Compute calculates composite risk indicators from resource metrics.
// Parameters:
//   cpuPct, memPct — CPU/memory usage percentage
//   connWaitPct    — connection wait queue saturation percentage
//   fdPct          — file descriptor usage percentage (used/fd_soft_limit * 100)
//   syscallErrorRate — syscall error rate (0-100)
//   ioLatencySpike   — I/O latency spike ratio (0-100)
//   backlogGrowth    — backlog queue growth rate (items/s)
func (ri *RiskIndicator) Compute(cpuPct, memPct, connWaitPct, fdPct float64,
	syscallErrorRate, ioLatencySpike float64,
	backlogGrowth float64) *RiskResult {

	// ── Saturation Index (USE) ──
	// SatIndex = w1×(CPU%) + w2×(Mem%) + w3×(ConnWait%)
	// Normalized to 0-1.
	satIndex := ri.CPUWeight*(cpuPct/100) +
		ri.MemWeight*(memPct/100) +
		ri.ConnWeight*(connWaitPct/100)

	// ── Dependency Risk Score ──
	// DepRisk = syscall_error_rate×0.5 + I/O_latency_spike×0.3 + fd_pressure×0.2
	fdPressure := math.Min(1, fdPct/100)
	depRisk := math.Min(1.0,
		syscallErrorRate/100*0.5+
			ioLatencySpike/100*0.3+
			fdPressure*0.2,
	)

	// ── OOM Risk Rate (cAdvisor style) ──
	// memory_working_set / memory_limit → OOM risk
	oomRisk := memPct / 100

	// ── Health Score ──
	// HealthScore = 100 - (SatIndex×40 + DepRisk×30 + BacklogGrowth×30)
	// BacklogGrowth capped contribution to avoid dominating.
	backlogContrib := math.Min(1, math.Abs(backlogGrowth)/10)
	healthScore := 100.0 - (satIndex*40 + depRisk*30 + backlogContrib*30)
	if healthScore < 0 {
		healthScore = 0
	}
	if healthScore > 100 {
		healthScore = 100
	}

	// ── Trend Direction ──
	trend := "stable"
	if backlogGrowth > 2.0 || satIndex > 0.7 {
		trend = "degrading"
	} else if healthScore < 50 {
		trend = "degrading"
	} else if healthScore > 90 && satIndex < 0.3 {
		trend = "improving"
	}

	return &RiskResult{
		HealthScore:      healthScore,
		SaturationIndex:  satIndex,
		DependencyRisk:   depRisk,
		BacklogGrowth:    backlogGrowth,
		OOMRiskRate:      oomRisk,
		CPUSaturationPct: cpuPct,
		MemSaturationPct: memPct,
		FDSaturationPct:  fdPct,
		HealthLevel:      healthLevel(healthScore),
		TrendDirection:   trend,
	}
}

// ComputeWithAlerts runs the full risk assessment pipeline and also returns
// anomaly alerts generated by the rule engine.
func (ri *RiskIndicator) ComputeWithAlerts(cpuPct, memPct, connWaitPct, fdPct float64,
	syscallErrorRate, ioLatencySpike float64,
	backlogGrowth float64,
	oomEvents int, cfsThrottledMs float64,
	ts time.Time) (*RiskResult, []AnomalyAlert) {

	result := ri.Compute(cpuPct, memPct, connWaitPct, fdPct,
		syscallErrorRate, ioLatencySpike, backlogGrowth)

	var alerts []AnomalyAlert

	// Rule 1: Memory leak trend (Heaptrack-style)
	if backlogGrowth > 1.0 && memPct > 50 {
		prob := clampFloat((backlogGrowth-1)/9, 0, 1)
		alerts = append(alerts, AnomalyAlert{
			Rule:        "mem_growth_trend",
			Condition:   "堆持续增长且无释放",
			Probability: prob,
			Severity:    alertSeverity(prob),
			Message:     "堆内存持续增长，检查是否忘记 free()",
			TeachingHint: "Heaptrack 趋势检测: 分配速率持续高于释放速率，意味着可能存在内存泄漏。检查 allocate 后是否有对应的 free。",
			Timestamp:   ts,
		})
	}

	// Rule 2: CPU anomaly
	if cpuPct > 90 {
		prob := clampFloat((cpuPct-90)/10, 0, 1)
		alerts = append(alerts, AnomalyAlert{
			Rule:        "cpu_abnormal",
			Condition:   "CPU > 90%",
			Probability: prob,
			Severity:    "warning",
			Message:     "CPU 使用率异常高，可能是死循环或密集计算",
			TeachingHint: "检查代码中是否有无限循环或大 O 复杂度过高的算法。考虑使用算法优化或分批处理。",
			Timestamp:   ts,
		})
	}

	// Rule 3: FD leak (cAdvisor style)
	if fdPct > 50 {
		prob := clampFloat((fdPct-50)/50, 0, 1)
		alerts = append(alerts, AnomalyAlert{
			Rule:        "fd_leak",
			Condition:   "FD 使用率持续增长",
			Probability: prob,
			Severity:    alertSeverity(prob),
			Message:     "文件描述符持续增长，检查是否忘记 close()!",
			TeachingHint: "每次 open()/socket()/pipe() 必须有对应的 close()。使用 valgrind --track-fds=yes 可追踪 FD 泄漏。",
			Timestamp:   ts,
		})
	}

	// Rule 4: OOM risk (cAdvisor cgroup style)
	if memPct > 80 {
		prob := clampFloat((memPct-80)/20, 0, 1)
		alerts = append(alerts, AnomalyAlert{
			Rule:        "oom_risk",
			Condition:   "内存使用 > 80% cgroup 限制",
			Probability: prob,
			Severity:    alertSeverity(prob),
			Message:     "内存使用接近 cgroup 限制，程序可能即将被 OOM Kill",
			TeachingHint: "cgroup memory.max 是硬限制，超过后进程将被 SIGKILL。优化内存使用或增大 cgroup 配额。",
			Timestamp:   ts,
		})
	}

	// Rule 5: CFS throttling (cAdvisor style)
	if cfsThrottledMs > 0 {
		alerts = append(alerts, AnomalyAlert{
			Rule:        "cfs_throttled",
			Condition:   "CPU CFS 节流 > 0",
			Probability: 1.0,
			Severity:    "warning",
			Message:     "CPU 配额耗尽，程序被 CFS 调度器节流!",
			TeachingHint: "CPU CFS (Completely Fair Scheduler) 限制了进程的 CPU 时间。节流意味着程序的 CPU 使用超过了 cgroup 配额。",
			Timestamp:   ts,
		})
	}

	// Rule 6: OOM Kill event
	if oomEvents > 0 {
		alerts = append(alerts, AnomalyAlert{
			Rule:        "oom_kill",
			Condition:   "检测到 OOM Kill 事件",
			Probability: 1.0,
			Severity:    "critical",
			Message:     "程序被 OOM Killer 终止!",
			TeachingHint: "OOM Killer 在系统内存耗尽时选择并杀死进程。查看被杀前的内存增长曲线，理解为什么会 OOM。",
			Timestamp:   ts,
		})
	}

	// Rule 7: Netdata-style multi-metric anomaly
	if cpuPct > 70 && memPct > 70 && syscallErrorRate > 10 {
		alerts = append(alerts, AnomalyAlert{
			Rule:        "multi_metric_anomaly",
			Condition:   "多指标同时偏离基线",
			Probability: clampFloat((cpuPct/100+memPct/100+syscallErrorRate/100)/3, 0, 1),
			Severity:    "warning",
			Message:     "多指标模式偏离正常实验基线，建议检查程序逻辑",
			Timestamp:   ts,
		})
	}

	return result, alerts
}

func healthLevel(score float64) string {
	switch {
	case score >= 85:
		return "healthy"
	case score >= 70:
		return "warning"
	case score >= 50:
		return "critical"
	default:
		return "severe"
	}
}

func alertSeverity(probability float64) string {
	switch {
	case probability >= 0.8:
		return "critical"
	case probability >= 0.5:
		return "warning"
	default:
		return "info"
	}
}

func clampFloat(v, lo, hi float64) float64 {
	if v < lo {
		return lo
	}
	if v > hi {
		return hi
	}
	return v
}
